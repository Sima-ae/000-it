def apply() -> None:
  root = Path("messages")
  missing_locales = []
  for path in sorted(root.glob("*.json")):
    code = path.stem
    data = json.loads(path.read_text())
    domains = DOMAINS.get(code) or DOMAINS["en"]
    shop = SHOP.get(code) or SHOP["en"]
    if code not in DOMAINS:
      missing_locales.append(code)

    dp = data.setdefault("domainsPage", {})
    for k, v in domains.items():
      dp[k] = v
      # Guard ICU placeholders
      if "{domain}" in DOMAINS["en"].get(k, "") and "{domain}" not in v:
        raise SystemExit(f"{code}.{k} missing {{domain}}: {v}")
      if "{order}" in DOMAINS["en"].get(k, "") and "{order}" not in v:
        raise SystemExit(f"{code}.{k} missing {{order}}: {v}")

    sh = data.setdefault("shop", {})
    for k, v in shop.items():
      sh[k] = v

    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    print(f"updated {code}")

  if missing_locales:
    print("fell back to EN for:", ", ".join(missing_locales))


if __name__ == "__main__":
  apply()
